#!/usr/bin/env bash
# =============================================================================
# 00_setup_modules.sh — automatically pick a working GNU toolchain on Sooner
# and write it to env/sooner_modules.sh. Nothing to edit by hand.
#
# You normally don't run this yourself: 02_build_wrf.slurm calls it when
# env/sooner_modules.sh doesn't exist yet. To run it manually (login node):
#     el9
#     bash scripts/build/00_setup_modules.sh
#
# How it works
#   1. Lists every netCDF-Fortran module built with a GNU toolchain
#      (EasyBuild "gompi-*" or "foss-*"), newest first.
#   2. Loads one. EasyBuild modules pull in their own dependencies, so this
#      also loads the matching GCC, OpenMPI, netCDF-C and HDF5.
#   3. Finds JasPer + libpng built with the same GCCcore version (for WPS).
#   4. Proves it works: compiles and runs a tiny Fortran program that uses
#      both MPI and netCDF. The first candidate that passes is saved.
# =============================================================================
set -u
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$REPO/env/sooner_modules.sh"

if ! type module >/dev/null 2>&1; then
    echo "ERROR: 'module' command not found. On the login node type 'el9' first." >&2
    exit 1
fi

newest() { sort -V | tail -n 1; }
avail() { module -t avail 2>&1 | grep -v ':$' | sed 's/(default)//; s/ *$//'; }

ALL="$(avail)"
mapfile -t CANDIDATES < <(echo "$ALL" | grep -E '^netCDF-Fortran/.*-(gompi|foss)-' | sort -Vr)
if [ "${#CANDIDATES[@]}" -eq 0 ]; then
    echo "No GNU netCDF-Fortran module found. Available netCDF modules:" >&2
    echo "$ALL" | grep -i netcdf >&2
    echo "Please email support@oscer.ou.edu and ask for netCDF-Fortran (gompi/foss)." >&2
    exit 1
fi

TEST_DIR="$(mktemp -d)"
cat > "$TEST_DIR/t.f90" <<'EOF'
program t
  use mpi
  use netcdf
  implicit none
  integer :: ierr, rank, ncid, st
  call MPI_Init(ierr)
  call MPI_Comm_rank(MPI_COMM_WORLD, rank, ierr)
  st = nf90_create('t.nc', NF90_CLOBBER, ncid)
  if (st /= NF90_NOERR) stop 1
  st = nf90_close(ncid)
  if (rank == 0) print '(a)', 'MPI+netCDF test OK'
  call MPI_Finalize(ierr)
end program t
EOF

for NF in "${CANDIDATES[@]}"; do
    echo "== trying $NF"
    module purge >/dev/null 2>&1
    module load "$NF" >/dev/null 2>&1 || { echo "   cannot load"; continue; }
    for c in gfortran mpif90 mpirun nf-config nc-config ncdump; do
        command -v "$c" >/dev/null || { echo "   missing $c"; continue 2; }
    done
    GCCV="${EBVERSIONGCCCORE:-$(gfortran -dumpfullversion)}"
    JASPER="$(echo "$ALL" | grep -E "^JasPer/.*-GCCcore-${GCCV}$" | newest)"
    PNG="$(echo "$ALL" | grep -E "^libpng/.*-GCCcore-${GCCV}$" | newest)"
    [ -n "$JASPER" ] && [ -n "$PNG" ] || { echo "   no JasPer/libpng for GCCcore-$GCCV"; continue; }
    module load "$JASPER" "$PNG" >/dev/null 2>&1 || { echo "   cannot load $JASPER $PNG"; continue; }

    ( cd "$TEST_DIR" && rm -f t.x t.nc &&
      mpif90 t.f90 -o t.x -I"$(nf-config --includedir)" $(nf-config --flibs) >build.log 2>&1 &&
      mpirun -np 1 ./t.x >run.log 2>&1 && grep -q OK run.log ) \
      || { echo "   compile/run test failed:"; tail -n 5 "$TEST_DIR"/*.log | sed 's/^/   /'; continue; }

    MPIV="$(module -t list 2>&1 | grep -E '^OpenMPI/' | head -n1)"
    cat > "$OUT" <<EOF
# Auto-generated by scripts/build/00_setup_modules.sh on $(date -u +%Y-%m-%d) — $(hostname -s)
# Loading netCDF-Fortran also loads its GCC, OpenMPI, netCDF-C, HDF5 dependencies.
# Delete this file and re-run the script to pick again (e.g. after OSCER updates).
MOD_NETCDF_F="$NF"
MOD_JASPER="$JASPER"
MOD_PNG="$PNG"
# For the record / README "Tested configuration":
#   gfortran  $(gfortran -dumpfullversion)
#   MPI       ${MPIV:-$(mpirun --version 2>&1 | head -n1)}
#   netCDF-C  $(nc-config --version)
#   netCDF-F  $(nf-config --version)
EOF
    rm -rf "$TEST_DIR"
    echo
    echo "Saved working module set to env/sooner_modules.sh:"
    cat "$OUT"
    exit 0
done

rm -rf "$TEST_DIR"
echo "No candidate passed. Send the output above to support@oscer.ou.edu (or to Claude)." >&2
exit 1
